//! zhbo-shaderc: a stand-in for bgfx's shaderc in the engine's build.
//!
//! It takes the same arguments the engine's `ggc_compile_bgfx_shader` passes to shaderc and writes
//! a `--bin2c` header of the same shape, but the array holds a zhbo shader blob (WGSL plus layout
//! reflection) that the wgpu runtime loads. Arguments it does not need (`-i`, `--platform`,
//! `--profile`, `-O`) are accepted and ignored.

use std::fmt::Write as _;
use std::process::ExitCode;

use zhbo_gfx::{blob, shader};

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("zhbo-shaderc: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let mut args = std::env::args().skip(1);
    let (mut input, mut output, mut name, mut ty, mut varying, mut defines) = (None, None, None, None, None, String::new());
    while let Some(a) = args.next() {
        let mut value = || args.next().ok_or_else(|| format!("{a} needs a value"));
        match a.as_str() {
            "-f" => input = Some(value()?),
            "-o" => output = Some(value()?),
            "--bin2c" => name = Some(value()?),
            "--type" => ty = Some(value()?),
            "--varyingdef" => varying = Some(value()?),
            "--define" => defines = value()?,
            "-i" | "--platform" | "-p" | "--profile" | "-O" => {
                value()?;
            }
            other => return Err(format!("unknown argument {other}")),
        }
    }
    let input = input.ok_or("-f is required")?;
    let output = output.ok_or("-o is required")?;
    let stage = match ty.as_deref() {
        Some("vertex" | "v") => shader::Stage::Vertex,
        Some("fragment" | "f") => shader::Stage::Fragment,
        other => return Err(format!("--type must be vertex or fragment, got {other:?}")),
    };
    let src = std::fs::read_to_string(&input).map_err(|e| format!("{input}: {e}"))?;
    let varying_path = varying.unwrap_or_else(|| {
        std::path::Path::new(&input).with_file_name("varying.def.sc").to_string_lossy().into_owned()
    });
    let varyings = shader::parse_varying_def(
        &std::fs::read_to_string(&varying_path).map_err(|e| format!("{varying_path}: {e}"))?,
    );
    // shaderc's --define is `A;B=1;C`.
    let defines: Vec<(&str, &str)> = defines
        .split(';')
        .map(str::trim)
        .filter(|d| !d.is_empty())
        .map(|d| d.split_once('=').unwrap_or((d, "1")))
        .collect();

    let blob = blob::build(&src, &varyings, stage, &defines).map_err(|e| format!("{input}: {e}"))?;
    let bytes = blob.encode();

    let name = name.unwrap_or_else(|| "shader".into());
    let mut header = String::with_capacity(bytes.len() * 6 + 256);
    let _ = writeln!(header, "// Generated by zhbo-shaderc from {input}. Do not edit.");
    let _ = writeln!(header, "static const uint8_t {name}[{}] =\n{{", bytes.len());
    for chunk in bytes.chunks(16) {
        header.push('\t');
        for b in chunk {
            let _ = write!(header, "0x{b:02x}, ");
        }
        header.push('\n');
    }
    header.push_str("};\n");
    std::fs::write(&output, header).map_err(|e| format!("{output}: {e}"))
}
