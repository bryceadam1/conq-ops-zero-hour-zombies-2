//! Builds `ConquerOps_BO2.big`: Black Ops II HUD art from the player's own `.ipak` packs, laid out in
//! one atlas texture with Zero Hour `MappedImage` definitions so the HUD can draw it by name.
//!
//! The images are identified by name hash (the names themselves are only in BO2's encrypted
//! fastfiles). Each was picked by eye from contact sheets (`zhbo-assets sheets`). The archive is
//! generated on the player's machine and must never be redistributed.

use crate::images;
use std::path::Path;
use zhbo_formats::big::write_archive;
use zhbo_formats::ipak::Ipak;
use zhbo_formats::iwi::Rgba;

/// Bump when the spec or layout changes so launchers regenerate the archive.
pub const VERSION: u32 = 7;
pub const ARCHIVE_NAME: &str = "ConquerOps_BO2.big";
pub const VERSION_FILE: &str = "Data\\ConquerOps\\bo2_hud_version.txt";
const TEXTURE: &str = "zhbo_bo2_hud.tga";
const ATLAS: u32 = 512;

pub struct Sprite {
    /// MappedImage name used by the HUD (see `zhbo_core::hud`).
    pub name: &'static str,
    pub pak: &'static str,
    pub hash: u32,
    pub size: (u32, u32),
    /// Top-left corner in the atlas.
    pub at: (u32, u32),
}

const fn digit(name: &'static str, hash: u32, slot: u32) -> Sprite {
    Sprite { name, pak: "mp.ipak", hash, size: (32, 64), at: (slot * 32, 0) }
}

/// The BO2 HUD art Conquer Ops uses.
pub const SPRITES: &[Sprite] = &[
    // The slanted HUD numerals.
    digit("ZHBO_BO2_Digit0", 0x0ad6_b469, 0),
    digit("ZHBO_BO2_Digit1", 0x1023_a304, 1),
    digit("ZHBO_BO2_Digit2", 0x0341_43b7, 2),
    digit("ZHBO_BO2_Digit3", 0x147c_846c, 3),
    digit("ZHBO_BO2_Digit4", 0x056b_fdc0, 4),
    digit("ZHBO_BO2_Digit5", 0x0566_ac71, 5),
    digit("ZHBO_BO2_Digit6", 0x0979_d350, 6),
    digit("ZHBO_BO2_Digit7", 0x0b81_1161, 7),
    digit("ZHBO_BO2_Digit8", 0x08c6_95e9, 8),
    digit("ZHBO_BO2_Digit9", 0x1aa6_7f7b, 9),
    digit("ZHBO_BO2_Slash", 0x010f_77fb, 10),
    // Blood splatter, used for the damage overlay.
    Sprite { name: "ZHBO_BO2_Blood", pak: "mp.ipak", hash: 0x0594_8908, size: (256, 256), at: (0, 64) },
    // Red-dot sight glow.
    Sprite { name: "ZHBO_BO2_RedDot", pak: "mp.ipak", hash: 0x023f_fb05, size: (128, 128), at: (256, 64) },
    // Cyan lock-on bracket (field computer targeting).
    Sprite { name: "ZHBO_BO2_Bracket", pak: "mp.ipak", hash: 0x0243_5b9e, size: (128, 128), at: (384, 64) },
];

#[derive(Debug, Default)]
pub struct Report {
    pub found: Vec<&'static str>,
    pub missing: Vec<(&'static str, String)>,
    /// The BO2 Generals: what was converted, or why not.
    pub generals: Option<Result<String, String>>,
}

/// Read the sprites from the BO2 install at `bo2_dir` and return the archive bytes.
pub fn build_archive(bo2_dir: &Path) -> Result<(Vec<u8>, Report), String> {
    let mut atlas = Rgba { width: ATLAS, height: ATLAS, pixels: vec![0; (ATLAS * ATLAS * 4) as usize] };
    let mut report = Report::default();
    let mut ini = String::from(
        "; Generated by zhbo-assets from the player's own Call of Duty: Black Ops II install.\n\
         ; Private data: do not redistribute.\n\n",
    );
    let mut paks: Vec<(&str, Ipak)> = Vec::new();
    for s in SPRITES {
        if !paks.iter().any(|(n, _)| *n == s.pak) {
            let pak = Ipak::open(bo2_dir.join("zone").join("all").join(s.pak)).map_err(|e| format!("{}: {e}", s.pak))?;
            paks.push((s.pak, pak));
        }
        let pak = &paks.iter().find(|(n, _)| *n == s.pak).unwrap().1;
        let groups = images::group_by_name(pak);
        let img = match groups.get(&s.hash).map(|parts| images::load(pak, parts)) {
            Some(Ok(img)) if (img.width, img.height) == s.size => img,
            Some(Ok(img)) => {
                report.missing.push((s.name, format!("unexpected size {}x{}", img.width, img.height)));
                continue;
            }
            Some(Err(e)) => {
                report.missing.push((s.name, e));
                continue;
            }
            None => {
                report.missing.push((s.name, "not in this install".into()));
                continue;
            }
        };
        blit(&mut atlas, &img, s.at);
        ini.push_str(&format!(
            "MappedImage {}\n  Texture = {TEXTURE}\n  TextureWidth = {ATLAS}\n  TextureHeight = {ATLAS}\n  \
             Coords = Left:{} Top:{} Right:{} Bottom:{}\n  Status = NONE\nEnd\n\n",
            s.name,
            s.at.0,
            s.at.1,
            s.at.0 + s.size.0 - 1, // Zero Hour's Coords are inclusive
            s.at.1 + s.size.1 - 1
        ));
        report.found.push(s.name);
    }
    let mut files = vec![
        (format!("Art\\Textures\\{TEXTURE}"), images::tga_bytes(&atlas)),
        ("Data\\INI\\MappedImages\\HandCreated\\ZHBO_BO2.ini".to_string(), ini.into_bytes()),
        (VERSION_FILE.to_string(), VERSION.to_string().into_bytes()),
    ];
    // The Generals as BO2 soldiers. On failure they keep their Zero Hour art.
    report.generals = Some(match crate::generals::files(bo2_dir) {
        Ok((general_files, summary)) => {
            files.extend(general_files);
            Ok(summary)
        }
        Err(e) => Err(e),
    });
    Ok((write_archive(&files), report))
}

fn blit(dst: &mut Rgba, src: &Rgba, at: (u32, u32)) {
    for y in 0..src.height.min(dst.height.saturating_sub(at.1)) {
        let s = (y * src.width * 4) as usize;
        let w = src.width.min(dst.width.saturating_sub(at.0));
        let d = (((at.1 + y) * dst.width + at.0) * 4) as usize;
        dst.pixels[d..d + (w * 4) as usize].copy_from_slice(&src.pixels[s..s + (w * 4) as usize]);
    }
}

/// Version stored in an existing archive, if it is one of ours.
pub fn archive_version(path: &Path) -> Option<u32> {
    let big = zhbo_formats::big::BigArchive::open(path).ok()?;
    let e = big.find(VERSION_FILE)?;
    String::from_utf8(big.read(e).ok()?).ok()?.trim().parse().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sprites_fit_the_atlas_without_overlap() {
        for (i, a) in SPRITES.iter().enumerate() {
            assert!(a.at.0 + a.size.0 <= ATLAS && a.at.1 + a.size.1 <= ATLAS, "{} outside atlas", a.name);
            for b in &SPRITES[i + 1..] {
                let overlap = a.at.0 < b.at.0 + b.size.0
                    && b.at.0 < a.at.0 + a.size.0
                    && a.at.1 < b.at.1 + b.size.1
                    && b.at.1 < a.at.1 + a.size.1;
                assert!(!overlap, "{} overlaps {}", a.name, b.name);
            }
        }
    }

    #[test]
    fn spec_matches_the_names_the_hud_draws() {
        let mut spec: Vec<&str> = SPRITES.iter().map(|s| s.name).collect();
        let mut hud: Vec<&str> = zhbo_core::hud::sprites::ALL.to_vec();
        spec.sort();
        hud.sort();
        assert_eq!(spec, hud);
    }

    #[test]
    #[ignore = "reads this machine's Black Ops II install"]
    fn builds_from_real_install() {
        let bo2 = zhbo_requirements::check_requirements().black_ops2.unwrap();
        let (bytes, report) = build_archive(&bo2.path).unwrap();
        println!("{report:?}");
        assert!(report.missing.is_empty());
        let dir = std::env::temp_dir().join("zhbo-hud-test");
        std::fs::create_dir_all(&dir).unwrap();
        let p = dir.join(ARCHIVE_NAME);
        std::fs::write(&p, bytes).unwrap();
        assert_eq!(archive_version(&p), Some(VERSION));
    }
}
