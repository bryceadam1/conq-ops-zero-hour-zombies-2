//! BO2's UI fonts (`fonts/720/<name>`, the families `CoD.fonts` names), from the player's
//! language zone `zone/<language>/<lang>_code_post_gfx_mp.ff`. Every font shares one alpha atlas
//! (`gamefonts_pc_720`, in `<lang>_base.ipak`). The atlas becomes a texture, each glyph a
//! MappedImage over it (`names::font_glyph`), and the metrics a text file the core lays text out
//! with (`zhbo_core::lui::font`, loaded from `names::FONTS_PATH`).

use crate::images;
use std::path::Path;
use zhbo_core::lui::font::Family;
use zhbo_core::names;
use zhbo_formats::font::Font;
use zhbo_formats::ipak::Ipak;
use zhbo_formats::iwi::Rgba;

/// The atlas texture's name in the archive.
const TEXTURE: &str = "zhbo_bo2_fonts.tga";

/// The language folders tried, with their zone prefixes.
const LANGUAGES: &[(&str, &str)] = &[("english", "en")];

/// The converted fonts: the archive files (atlas, MappedImages, metrics) and a summary.
pub fn files(bo2_dir: &Path) -> Result<(Vec<(String, Vec<u8>)>, String), String> {
    let (dir, prefix) = LANGUAGES
        .iter()
        .find(|(dir, prefix)| bo2_dir.join("zone").join(dir).join(format!("{prefix}_code_post_gfx_mp.ff")).is_file())
        .ok_or("no language zone with the UI fonts")?;
    let zone_path = bo2_dir.join("zone").join(dir).join(format!("{prefix}_code_post_gfx_mp.ff"));
    let file = std::fs::read(&zone_path).map_err(|e| format!("{}: {e}", zone_path.display()))?;
    let ff = zhbo_formats::fastfile::read(&file).map_err(|e| e.to_string())?;
    let zone = zhbo_formats::t6zone::load(&ff).map_err(|e| e.to_string())?;
    let fonts: Vec<Font> = zhbo_formats::font::all(&zone)
        .map_err(|e| e.to_string())?
        .into_iter()
        .filter(|f| Family::ALL.iter().any(|fam| short(&f.name) == fam.file()))
        .collect();
    if fonts.is_empty() {
        return Err("the language zone has no UI fonts".into());
    }
    // Every UI font draws from the same atlas; refuse a zone where they differ rather than
    // mapping glyphs onto the wrong page.
    let hashes: Vec<u32> = fonts
        .iter()
        .map(|f| f.material.as_ref().and_then(|m| m.textures.iter().find_map(|t| t.image.as_ref())).map_or(0, |i| i.stream_hash))
        .collect();
    let hash = hashes[0];
    if hash == 0 || hashes.iter().any(|h| *h != hash) {
        return Err(format!("the UI fonts do not share one streamed atlas ({hashes:08x?})"));
    }
    let pak_path = bo2_dir.join("zone").join(dir).join(format!("{prefix}_base.ipak"));
    let pak = Ipak::open(&pak_path).map_err(|e| format!("{}: {e}", pak_path.display()))?;
    let groups = images::group_by_name(&pak);
    let atlas = groups.get(&hash).ok_or("the font atlas is not in the language pack").and_then(|parts| images::load(&pak, parts).map_err(|_| "the font atlas does not decode"))?;
    let (metrics, mapped) = describe(&fonts, &atlas);
    let summary = format!("{} fonts, {} glyphs, atlas {}x{}", fonts.len(), mapped.matches("MappedImage").count(), atlas.width, atlas.height);
    Ok((
        vec![
            (format!("Art\\Textures\\{TEXTURE}"), images::tga_bytes(&atlas)),
            ("Data\\INI\\MappedImages\\HandCreated\\ZHBO_BO2Fonts.ini".to_string(), mapped.into_bytes()),
            (names::FONTS_PATH.to_string(), metrics.into_bytes()),
        ],
        summary,
    ))
}

/// `fonts/720/bigFont` -> `bigFont`.
fn short(name: &str) -> &str {
    name.rsplit('/').next().unwrap_or(name)
}

/// The metrics file and the MappedImage INI for `fonts` over `atlas`.
fn describe(fonts: &[Font], atlas: &Rgba) -> (String, String) {
    let mut metrics = String::from("; BO2 UI fonts, converted from the player's own install. Do not redistribute.\n");
    let mut mapped = String::from("; Generated by zhbo-assets from the player's own Black Ops II install. Do not redistribute.\n\n");
    for f in fonts {
        let name = short(&f.name);
        metrics.push_str(&format!("font {name} {}\n", f.pixel_height));
        for g in &f.glyphs {
            let image = names::font_glyph(name, g.letter.into());
            metrics.push_str(&format!("g {} {} {} {} {} {} {image}\n", g.letter, g.x0, g.y0, g.dx, g.width, g.height));
            if g.width == 0 || g.height == 0 {
                continue;
            }
            // The glyph's atlas rectangle in pixels; Zero Hour's Coords are inclusive.
            let left = (g.s0 * atlas.width as f32).round() as u32;
            let top = (g.t0 * atlas.height as f32).round() as u32;
            let right = ((g.s1 * atlas.width as f32).round() as u32).max(left + 1) - 1;
            let bottom = ((g.t1 * atlas.height as f32).round() as u32).max(top + 1) - 1;
            mapped.push_str(&format!(
                "MappedImage {image}\n  Texture = {TEXTURE}\n  TextureWidth = {}\n  TextureHeight = {}\n  \
                 Coords = Left:{left} Top:{top} Right:{right} Bottom:{bottom}\n  Status = NONE\nEnd\n\n",
                atlas.width, atlas.height
            ));
        }
    }
    (metrics, mapped)
}

#[cfg(test)]
mod tests {
    use super::*;
    use zhbo_formats::font::Glyph;

    #[test]
    fn describes_glyphs_in_the_core_s_format() {
        let glyph = |letter, w, h| Glyph { letter, x0: 1, y0: -39, dx: 18, width: w, height: h, s0: 0.25, t0: 0.5, s1: 0.28125, t1: 0.53125 };
        let font = Font { name: "fonts/720/bigFont".into(), pixel_height: 48, glyphs: vec![glyph(65, 16, 32), glyph(32, 0, 0)], kerning: Vec::new(), material: None };
        let atlas = Rgba { width: 512, height: 1024, pixels: Vec::new() };
        let (metrics, mapped) = describe(&[font], &atlas);
        // The core parses exactly what the converter writes.
        let parsed = zhbo_core::lui::font::parse(&metrics);
        let big = &parsed["bigFont"];
        assert_eq!(big.pixel_height, 48.0);
        assert_eq!(big.glyphs[&'A'].image, "ZHBO_Glyph_bigFont_65");
        assert_eq!(big.glyphs[&' '].dx, 18.0, "a space still advances");
        // One MappedImage per drawn glyph: 0.25 x 512 = 128 .. 144 (16 px), 512 .. 544 (32 px).
        assert_eq!(mapped.matches("MappedImage").count(), 1);
        assert!(mapped.contains("Coords = Left:128 Top:512 Right:143 Bottom:543"), "{mapped}");
    }

    #[test]
    #[ignore = "reads this machine's Black Ops II install"]
    fn converts_the_real_fonts() {
        let bo2 = std::env::var("ZHBO_BO2_DIR").expect("set ZHBO_BO2_DIR");
        let (files, summary) = files(Path::new(&bo2)).unwrap();
        println!("{summary}");
        let metrics = String::from_utf8_lossy(&files.iter().find(|(p, _)| p == names::FONTS_PATH).unwrap().1).into_owned();
        let parsed = zhbo_core::lui::font::parse(&metrics);
        for fam in Family::ALL {
            let f = parsed.get(fam.file()).unwrap_or_else(|| panic!("{} converted", fam.file()));
            assert!(f.glyphs.contains_key(&'A') && f.glyphs.contains_key(&'0'), "{}", fam.file());
        }
        assert_eq!(parsed["bigFont"].pixel_height, 48.0, "Big is CoD.textSize.Big (48) in English");
    }
}
