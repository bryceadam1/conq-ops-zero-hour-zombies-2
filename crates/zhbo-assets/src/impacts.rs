//! BO2's `FxImpactTable` as the mod's `Data\ConquerOps\impacts.txt` (R8d).
//!
//! BO2's weapon carries a bucket (`WeaponDef.impactType`) and the engine reads the table's cell for
//! that bucket and the surface that was hit. The mod's own surface vocabulary is
//! `zhbo_core::impacts::Surface` (12 slots, every one reachable from Zero Hour data); this module
//! maps it to BO2's 32-entry `materialSurfType_t` and converts the cells, deduped by FXList name
//! like every other effect.
//!
//! The projectile impact types (grenades, launchers, rockets, bolts) get their cells too, and their
//! sounds: BO2's blast plays the row's cell and the type's family alias `<family>_<surface>` for the
//! surface it went off on (`zhbo_formats::fx::ImpactKind`), so both land here as rows keyed by
//! `impactType` and surface, and the sim/client pick by what was hit.

use crate::fx::Converted;
use zhbo_core::impacts::Surface;
use zhbo_formats::fx;
use zhbo_formats::iwi::Rgba;
use zhbo_formats::t6zone::Zone;

/// BO2's `materialSurfType_t` index for a mod slot. `Surface::Flesh` never reaches this table (it
/// uses the four `flesh[]` cells), so it maps to `SURF_TYPE_FLESH` only as a marker.
pub fn bo2_surface(s: Surface) -> usize {
    match s {
        Surface::Default => fx::surface::DEFAULT,
        Surface::Flesh => fx::surface::FLESH,
        Surface::Metal => fx::surface::METAL,
        Surface::Concrete => fx::surface::CONCRETE,
        Surface::Dirt => fx::surface::DIRT,
        Surface::Grass => fx::surface::GRASS,
        Surface::Asphalt => fx::surface::ASPHALT,
        Surface::Sand => fx::surface::SAND,
        Surface::Snow => fx::surface::SNOW,
        Surface::Rock => fx::surface::ROCK,
        Surface::Wood => fx::surface::WOOD,
        Surface::Water => fx::surface::WATER,
    }
}

/// The converted table text for the impact types the converted weapons carry (bullets and
/// projectiles alike: each type reads its `fx::ImpactKind` row). Returns the text and the types
/// that have no table row (the summary names them; the install-gated test fails on them).
pub fn table_text(zone: &Zone, impact_types: &[u32], effects: &mut Converted, paks: &dyn Fn(u32) -> Option<Rgba>) -> (String, Vec<u32>) {
    let mut text = String::from(
        "; BO2's impact table: `impact <impactType> <surface> <fxlist>` for non-flesh hits,\n\
         ; `flesh <impactType> <FxFleshType 0..3> <fxlist>` for blood and `sound <impactType> <surface> \
         <event>` for a blast's sound. Generated by Conquer Ops from the player's own Black Ops II \
         install. Do not redistribute.\n",
    );
    let mut unmapped = Vec::new();
    for &t in impact_types {
        let Some(entry) = fx::impact_kind(t).map(|k| k.row) else {
            unmapped.push(t);
            continue;
        };
        // Every slot except flesh (its own four cells) and default (written once, as the fallback).
        for s in Surface::ALL.into_iter().filter(|s| !matches!(s, Surface::Flesh | Surface::Default)) {
            if let Some(e) = fx::impact(zone, entry, bo2_surface(s)) {
                let name = effects.add(&e, paks);
                text.push_str(&format!("impact {t} {} {name}\n", s.name()));
            }
        }
        // The bucket's own default cell: what a surface without a cell falls back to.
        if let Some(e) = fx::impact(zone, entry, bo2_surface(Surface::Default)) {
            let name = effects.add(&e, paks);
            text.push_str(&format!("impact {t} default {name}\n"));
        }
        for v in 0..4 {
            if let Some(e) = fx::impact_flesh_variant(zone, entry, v) {
                let name = effects.add(&e, paks);
                text.push_str(&format!("flesh {t} {v} {name}\n"));
            }
        }
    }
    (text, unmapped)
}

/// BO2's impact sounds for `impact_types` (bullets and blasts alike): for each mod surface the
/// type's family alias `<family>_<surface>` (BO2's `FUN_004d42d0` naming over its surface names,
/// which the mod's slots share — `Surface::name`), when the install has it (`has_alias`,
/// case-insensitive like BO2's hash), else `NONE`: BO2's hash miss plays nothing
/// (`FUN_0082df80`), so a type's row set is complete and a missing alias is silent rather than a
/// fallback (the shotgun's `prj_bulletspray_small` ships only exit and ricochet aliases, so its
/// entry hits are silent). Types without a family (`grenade_bounce`, `projectile_dud`: def fields
/// the mod does not carry) get no rows. Returns the `sound` rows and the aliases, each once, for
/// the sound conversion (its secondary chain comes with it).
pub fn sound_rows(impact_types: &[u32], has_alias: &dyn Fn(&str) -> bool) -> (String, Vec<String>) {
    let mut text = String::new();
    let mut aliases: Vec<String> = Vec::new();
    for &t in impact_types {
        let Some(family) = fx::impact_kind(t).and_then(|k| k.sound_family) else { continue };
        for s in Surface::ALL {
            let alias = format!("{family}_{}", s.name());
            if !has_alias(&alias) {
                text.push_str(&format!("sound {t} {} {}\n", s.name(), zhbo_core::sounds::NO_SOUND));
                continue;
            }
            text.push_str(&format!("sound {t} {} {}\n", s.name(), zhbo_core::names::def_sound_event(&alias)));
            if !aliases.contains(&alias) {
                aliases.push(alias);
            }
        }
    }
    (text, aliases)
}

/// The projectile impact types of the defs that go off (explode, stun, EMP, smoke), sorted, each once.
pub fn blast_types(defs: &[zhbo_core::weapons::WeaponDef]) -> Vec<u32> {
    use zhbo_core::weapons::Effect;
    let mut t: Vec<u32> = defs
        .iter()
        .filter(|d| matches!(d.effect, Effect::Explode | Effect::Stun | Effect::Emp | Effect::Smoke))
        .map(|d| d.impact_type.max(0) as u32)
        .filter(|t| !fx::is_bullet(*t) && fx::impact_kind(*t).is_some())
        .collect();
    t.sort_unstable();
    t.dedup();
    t
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_slot_maps_to_a_distinct_bo2_surface() {
        let mut seen = std::collections::BTreeSet::new();
        for s in Surface::ALL {
            let i = bo2_surface(s);
            assert!(i < 32, "{s:?} -> {i}");
            assert!(seen.insert(i), "{s:?} collides at {i}");
        }
        // Flesh is BO2's own bit and is deliberately not a non-flesh cell.
        assert_eq!(bo2_surface(Surface::Flesh), fx::surface::FLESH);
        assert_eq!(bo2_surface(Surface::Default), fx::surface::DEFAULT);
    }

    #[test]
    fn a_type_gets_its_familys_alias_per_surface_and_none_where_bo2_has_none() {
        // The install has the grenade family on dirt and concrete (and the default), the small
        // bullet's on concrete only, nothing of the shotgun's entry family.
        let have = ["wpn_grenade_explode_default", "WPN_GRENADE_EXPLODE_DIRT", "wpn_grenade_explode_concrete", "prj_bullet_impact_small_concrete"];
        let has = |a: &str| have.iter().any(|h| h.eq_ignore_ascii_case(a));
        let (text, aliases) = sound_rows(&[1, 5, 6, 7, 99], &has);
        let rows: Vec<_> = zhbo_core::impacts::parse_sounds(&text).into_iter().map(|r| (r.impact_type, r.surface, r.event)).collect();
        let cell = |t, s| zhbo_core::impacts::find_sound(&rows, t, s).map(String::as_str);
        // Every surface of every family type has a row; a missing alias is NONE (silent).
        for t in [1, 5, 7] {
            assert_eq!(rows.iter().filter(|r| r.0 == t).count(), Surface::ALL.len(), "type {t}");
        }
        assert!(!rows.iter().any(|r| r.0 == 6 || r.0 == 99), "no family, no rows");
        assert_eq!(cell(7, Surface::Dirt), Some("ZHBO_BO2_Snd_wpn_grenade_explode_dirt"));
        assert_eq!(cell(7, Surface::Concrete), Some("ZHBO_BO2_Snd_wpn_grenade_explode_concrete"));
        assert_eq!(cell(7, Surface::Water), Some(zhbo_core::sounds::NO_SOUND));
        assert_eq!(cell(1, Surface::Concrete), Some("ZHBO_BO2_Snd_prj_bullet_impact_small_concrete"));
        assert_eq!(cell(1, Surface::Dirt), Some(zhbo_core::sounds::NO_SOUND));
        assert!(rows.iter().filter(|r| r.0 == 5).all(|r| r.2 == zhbo_core::sounds::NO_SOUND), "the shotgun's entry family is empty");
        assert_eq!(aliases, ["prj_bullet_impact_small_concrete", "wpn_grenade_explode_default", "wpn_grenade_explode_concrete", "wpn_grenade_explode_dirt"]);
    }

    #[test]
    fn the_impact_kinds_are_bo2s_switch() {
        // FUN_00533210's rows for an entry hit, and FUN_004d4440's families.
        let row = |t| fx::impact_kind(t).map(|k| k.row);
        assert_eq!([1, 2, 3, 4, 5].map(row), [Some(0), Some(3), Some(7), Some(9), Some(5)]);
        assert_eq!([7, 8, 9, 10, 12, 13, 14, 15].map(row), [Some(12), Some(12), Some(13), Some(14), Some(16), Some(17), Some(19), Some(20)]);
        assert_eq!(row(0), None);
        let family = |t| fx::impact_kind(t).and_then(|k| k.sound_family);
        assert_eq!(family(8), Some("wpn_rifle_grenade"));
        assert_eq!(family(10), Some("wpn_rocket_explode"));
        assert_eq!(family(12), Some("wpn_mortar_shell"));
        assert_eq!(family(13), Some("wpn_tank_shell"));
        assert_eq!(family(6), None, "a bounce plays the def's own per-surface table");
        assert_eq!(fx::bullet_entry(1), Some(0), "the small bullet's entry row, not its exit row");
        assert_eq!(fx::bullet_entry(7), None);
    }
}
