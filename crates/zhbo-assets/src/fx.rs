/// Milliseconds per Zero Hour logic frame.
const MS_PER_FRAME: f32 = 1000.0 / 30.0;
/// BO2's gravity (800 in/s^2) in Zero Hour units per frame^2 (the one BO2-inches factor).
const G_PER_FRAME2: f32 = 800.0 / 900.0 * zhbo_core::units::ZH_PER_INCH;
/// Largest side of an effect texture.
const FX_TEXTURE_MAX: u32 = 256;

/// Inches to Zero Hour units (`zhbo_core::units::inches`).
fn units(inches: f32) -> f32 {
    zhbo_core::units::inches(inches)
}

/// The Zero Hour name of a converted BO2 effect (the registry's builder, `names::bo2_fx`).
pub fn fxlist_name(effect: &str) -> String {
    zhbo_core::names::bo2_fx(effect)
}

/// The name of an effect's framed copy ([`Converted::add_framed`]).
pub fn framed_fxlist_name(effect: &str) -> String {
    format!("{}_Framed", fxlist_name(effect))
}

