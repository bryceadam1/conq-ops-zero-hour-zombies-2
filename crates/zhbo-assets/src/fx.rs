/// Converted effects: the particle system and FXList INI text, and their textures.
#[derive(Default)]
pub struct Converted<'a> {
    /// The zones an element's reference-stub material resolves in ([`fx::bind_materials`]).
    pool: &'a [&'a Zone],
    pub particles: String,
    pub fxlists: String,
    pub textures: BTreeMap<String, Vec<u8>>,
    /// Effects already converted, by FXList name.
    done: std::collections::BTreeSet<String>,
    /// Each converted FXList's particle systems and whether they take the spawner's matrix, for
    /// the lists built from them ([`Converted::placed`], [`Converted::compose`]).
    lists: BTreeMap<String, (Vec<Placed>, bool)>,
    /// The nugget text of every FXList written, by name.
    bodies: BTreeMap<String, String>,
    /// The role each converted FXList was made for ([`Role`]).
    roles: BTreeMap<String, Role>,
    /// Images an element named that the packs did not have (its element is not drawn).
    pub missing: std::collections::BTreeSet<String>,
}

impl<'a> Converted<'a> {
    /// A converter whose effects' stub materials bind to the full ones in `pool` (highest priority
    /// first), as BO2's asset pool binds them.
    pub fn with_pool(pool: &'a [&'a Zone]) -> Self {
        Converted { pool, ..Default::default() }
    }

    /// Convert `effect` (with the effects its runners start) into an FXList played upright with no
    /// frame, in the role `role` ([`Role`]: its priority); returns its name. Looping parts run for
    /// the effect's own looping life (at most 20 s).
    pub fn add_as(&mut self, effect: &Effect, role: Role, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> String {
        let looping_secs = (effect.looping_life_msec as f32 / 1000.0).clamp(1.0, 20.0);
        self.convert(effect, &fxlist_name(&effect.name), Play { looping_secs, role, orient: false }, paks, None)
    }

    /// [`Converted::add_as`] a blast ([`Role::Blast`]): an explosion, a flash grenade's burst, an
    /// equipment's death.
    pub fn add(&mut self, effect: &Effect, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> String {
        self.add_as(effect, Role::Blast, paks)
    }

    /// An area effect standing `secs` (BO2's timed effect entity, `spawntimedfx`: its looping parts
    /// emit until the entity is freed, the rest play out their own life), as [`Role::Area`]: the
    /// smoke screen.
    pub fn add_area(&mut self, effect: &Effect, secs: f32, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> String {
        self.convert(effect, &fxlist_name(&effect.name), Play { looping_secs: secs, role: Role::Area, orient: false }, paks, None)
    }

    /// [`Converted::add_as`] for an effect played on a frame whose X is BO2's effect X: a bullet's
    /// impact (the bridge passes the surface frame, X along the normal), a muzzle flash at its
    /// flash bone (X down the barrel). Its systems take the spawner's matrix (`OrientToObject`) and
    /// keep BO2's axes, offsets and velocities included. Named apart from the world copy
    /// ([`framed_fxlist_name`]): the same BO2 effect can be a blast's (played upright, no frame)
    /// and a bullet's.
    pub fn add_framed(&mut self, effect: &Effect, role: Role, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> String {
        let looping_secs = (effect.looping_life_msec as f32 / 1000.0).clamp(1.0, 20.0);
        self.convert(effect, &framed_fxlist_name(&effect.name), Play { looping_secs, role, orient: true }, paks, None)
    }

    /// [`Converted::add_as`] for an effect whose model elements (a shell casing) should be drawn as
    /// sprites from the model's own colour map ([`Role::Shell`]). A shell is spawned at the posed
    /// `tag_brass`, whose X is BO2's eject direction, so its systems take the bone's matrix and keep
    /// BO2's axes. The `zones` are tried in order: a patch zone's copy of a shell model or its
    /// material can be a reference stub while the base zone (or the patch zone's material asset)
    /// carries the real one.
    pub fn add_shell(&mut self, effect: &Effect, zones: &[&Zone], paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> String {
        let looping_secs = (effect.looping_life_msec as f32 / 1000.0).clamp(1.0, 20.0);
        self.convert(effect, &fxlist_name(&effect.name), Play { looping_secs, role: Role::Shell, orient: true }, paks, Some(zones))
    }

    fn convert(&mut self, effect: &Effect, name: &str, play: Play, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>, zones: Option<&[&Zone]>) -> String {
        let name = name.to_string();
        if !self.done.insert(name.clone()) {
            // One BO2 effect played in two roles (`fx_missing_impact` is a rocket's blast cell and a
            // bounce's): it takes the higher priority, whichever came first.
            let had = self.roles.get(&name).copied();
            if let Some(had) = had.filter(|h| h.rank() < play.role.rank()) {
                for sys in self.lists.get(&name).map(|(s, _)| s.clone()).unwrap_or_default() {
                    let old = format!("ParticleSystem {}\n  Priority = {}\n", sys.system, had.priority());
                    let new = format!("ParticleSystem {}\n  Priority = {}\n", sys.system, play.role.priority());
                    self.particles = self.particles.replace(&old, &new);
                }
                self.roles.insert(name.clone(), play.role);
            }
            return name;
        }
        self.roles.insert(name.clone(), play.role);
        let mut bound;
        let effect = if self.pool.is_empty() {
            effect
        } else {
            bound = effect.clone();
            zhbo_formats::fx::bind_materials(&mut bound, self.pool);
            &bound
        };
        let mut systems = Vec::new();
        let mut lights = String::new();
        let at = Spawn::START;
        self.add_elems(effect, at, play, &name, paks, zones, &mut systems, &mut lights);
        let mut body = lights;
        body.push_str(&fxlist_particles(&systems, play.orient));
        self.lists.insert(name.clone(), (systems, play.orient));
        self.write(&name, body);
        name
    }

    fn write(&mut self, name: &str, body: String) {
        self.fxlists.push_str(&format!("FXList {name}\n{body}End\n\n"));
        self.bodies.insert(name.to_string(), body);
    }

    /// A copy of the converted FXList `src`'s particle systems spawned `offset` (Zero Hour units)
    /// from the spawner and turned by `rotate_deg` about its X, then Y, then Z (Zero Hour's
    /// `RotateX/Y/Z`, post-multiplied onto the spawner's matrix): BO2's third-person shell, which
    /// plays at the world model's `tag_brass`, spawned from the flash bone the shot comes from.
    /// `None` when `src` was not converted or has nothing to draw.
    pub fn placed(&mut self, src: &str, name: &str, offset: [f32; 3], rotate_deg: [f32; 3]) -> Option<String> {
        if self.bodies.contains_key(name) {
            return Some(name.to_string());
        }
        let (systems, orient) = self.lists.get(src).cloned().filter(|(s, _)| !s.is_empty())?;
        let rotate = format!("    RotateX = {:.2}\n    RotateY = {:.2}\n    RotateZ = {:.2}\n", rotate_deg[0], rotate_deg[1], rotate_deg[2]);
        let orient = if orient { "    OrientToObject = Yes\n" } else { "" };
        let body = systems
            .iter()
            .map(|s| {
                let o = [offset[0] + s.offset[0], offset[1] + s.offset[1], offset[2] + s.offset[2]];
                format!("  ParticleSystem\n    Name = {}\n{orient}    Offset = X:{:.3} Y:{:.3} Z:{:.3}\n{rotate}  End\n", s.system, o[0], o[1], o[2])
            })
            .collect();
        self.write(name, body);
        Some(name.to_string())
    }

    /// One FXList playing the written FXLists `parts` together (the ones not written are skipped),
    /// then `extra` nugget text; `None` when nothing is left.
    pub fn compose(&mut self, name: &str, parts: &[&str], extra: &str) -> Option<String> {
        if self.bodies.contains_key(name) {
            return Some(name.to_string());
        }
        let mut body: String = parts.iter().filter_map(|p| self.bodies.get(*p)).map(String::as_str).collect();
        body.push_str(extra);
        if body.is_empty() {
            return None;
        }
        self.write(name, body);
        Some(name.to_string())
    }

    /// A BO2 tracer (`TracerDef`) as an FXList of one Zero Hour `Tracer` nugget, which flies a
    /// beam from the flash bone towards the shot's end (`TracerFXNugget`). `tint` is the tracer
    /// material's mean colour; `probability` < 1 only where no sim decides the cadence.
    pub fn tracer(&mut self, t: &zhbo_formats::weapon::Tracer, tint: [f32; 3], probability: f32) -> String {
        let name = tracer_fxlist(&t.name, probability);
        if !self.bodies.contains_key(&name) {
            self.write(&name, tracer_nugget(t, tint, probability));
        }
        name
    }

    /// The particle systems a converted FXList starts, in order (a projectile's trail is attached
    /// to its drawable by name: `ParticleSysBone`).
    pub fn systems(&self, list: &str) -> Vec<String> {
        self.lists.get(list).map(|(s, _)| s.iter().map(|p| p.system.clone()).collect()).unwrap_or_default()
    }

    /// The nugget text of a written FXList.
    pub fn body(&self, name: &str) -> Option<&str> {
        self.bodies.get(name).map(String::as_str)
    }

    #[allow(clippy::too_many_arguments)]
    fn add_elems(&mut self, effect: &Effect, at: Spawn, play: Play, prefix: &str, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>, zones: Option<&[&Zone]>, systems: &mut Vec<Placed>, lights: &mut String) {
        let orient = play.orient;
        for el in &effect.elems {
            // Emission elements are spawned by their effect's movement (`emitDist`), never on its
            // start; a one-shot element BO2 spawns none of (`count` 0 + 0) is not drawn.
            if el.emission || (!el.looping && el.count.max() < 1.0) {
                continue;
            }
            if el.kind == kind::RUNNER {
                // The runner's effect starts where and when the runner spawns.
                let child_at = at.run(el, play.looping_secs);
                if child_at.times <= 0.0 {
                    continue;
                }
                for child in &el.children {
                    self.add_elems(child, child_at, play, prefix, paks, zones, systems, lights);
                }
                continue;
            }
            if el.kind == kind::OMNI_LIGHT {
                lights.push_str(&light_pulse(el));
                continue;
            }
            // A blast's decal (its scorch) is Zero Hour's own scorch mark on the ground, BO2's size.
            // Hits are not: Zero Hour marks only terrain, and a bullet's hole is on what it struck.
            if el.kind == kind::DECAL {
                if play.role == Role::Blast && !orient {
                    lights.push_str(&scorch(el));
                }
                continue;
            }
            // A model element (BO2's ejected shell casing) becomes a sprite of the model's own
            // colour map: Zero Hour's FXList has no model element.
            if el.kind == kind::MODEL {
                let Some(zones) = zones else { continue };
                for model_name in &el.models {
                    // A patch zone's copy of a shell model can be a reference stub (BO2's
                    // comma-prefixed asset) with no surfaces; the base zone has the real model.
                    let Some(model) = zones.iter().find_map(|z| xmodel::find(z, model_name).ok().filter(|m| !m.surfaces.is_empty())) else { continue };
                    let Some(mat) = model.materials.iter().flatten().next() else { continue };
                    // The base zone's inline material can be a stub with no textures; its real
                    // material (mc/mtl_fx_shell) is an asset in the patch zone.
                    let colour = mat.color_map().cloned().or_else(|| {
                        zones.iter().find_map(|z| xmodel::find_material(z, &mat.name).and_then(|m| m.color_map().cloned()))
                    });
                    let Some(img) = colour else { continue };
                    let Some(tex) = self.texture(&img.name, img.key(), (1, 1), 1, paks) else { continue };
                    let sys = format!("{prefix}_shell{}", systems.len());
                    if let Some(ini) = model_particle_system(&sys, el, &tex.file, at, play) {
                        self.particles.push_str(&ini);
                        systems.push(Placed { system: sys, offset: frame_vec(orient, add3(at.origin, origin_centre(el))) });
                    }
                }
                continue;
            }
            // The effect each particle starts where it dies (`effectOnDeath`: the smoke grenade's
            // falling wisp leaves its lingering puffs), as a runner at the end of its life.
            if let Some(death) = &el.on_death {
                let mut then = at.run(el, play.looping_secs);
                then.delay_ms += 0.5 * (el.life_msec.min() + el.life_msec.max());
                then.origin = add3(then.origin, death_travel(el, !orient));
                if then.times > 0.0 {
                    self.add_elems(death, then, play, prefix, paks, zones, systems, lights);
                }
            }
            if !kind::is_sprite(el.kind) || el.vis.is_empty() {
                continue;
            }
            // A moving effect's trail element is a ribbon through the points it leaves, drawn
            // with ribbon art (the RPG's `fxt_smk_trail`, 512 x 64). Zero Hour has no ribbon: as
            // sprites the strip tiles the view with streaks, and as a `STREAK` it crosses the
            // shooter's eye in screen-wide polygons (both seen on the SMAW). On a projectile it is
            // left out; its puffs, flares and fire are drawn.
            if el.kind == kind::TRAIL && play.role == Role::Trail {
                continue;
            }
            let Some(m) = el.materials.first() else { continue };
            if m.name.contains("distortion") {
                continue; // a screen-space ripple Zero Hour can't draw
            }
            let Some(img) = m.color_map() else { continue };
            let Some(tex) = self.texture(&img.name, img.key(), el.atlas, el.flipbook.frames, paks) else { continue };
            // As BO2 blends the material: glows add, smoke and debris mix by alpha (premultiplied
            // art too, the nearest Zero Hour has). Without a render state, art with no real alpha adds.
            let additive = match m.blend() {
                Blend::Additive { .. } => true,
                Blend::Alpha | Blend::Premultiplied => false,
                Blend::Opaque | Blend::AlphaTest => tex.opaque,
            };
            let sys = format!("{prefix}_{}", systems.len());
            if let Some(ini) = particle_system(&sys, el, &tex.file, additive, tex.grid, at, play) {
                self.particles.push_str(&ini);
                systems.push(Placed { system: sys, offset: frame_vec(orient, add3(at.origin, origin_centre(el))) });
            }
        }
    }

    /// [`Converted::texture`] for the headless preview (`fx_preview`): the BO2 row draws elements
    /// the conversion may skip.
    pub fn preview_texture(&mut self, image: &str, key: zhbo_formats::ipak::ImageKey, atlas: (u32, u32), frames: u32, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) {
        self.texture(image, key, atlas, frames, paks);
    }

    /// The texture for a BO2 image. A flipbook atlas (`atlas` columns × rows, `frames` of its cells
    /// in use) is laid out again as the square grid Zero Hour's point group draws from (host patch
    /// 0025's `FrameGrid`; [`Grid`]); with one frame in use only the first cell is drawn.
    fn texture(&mut self, image: &str, key: zhbo_formats::ipak::ImageKey, atlas: (u32, u32), frames: u32, paks: &dyn Fn(zhbo_formats::ipak::ImageKey) -> Option<zhbo_formats::iwi::Rgba>) -> Option<Tex> {
        let cells = (atlas.0.max(1) * atlas.1.max(1)).min(MAX_FRAMES);
        let grid = Grid::of(frames.min(cells));
        let file = texture_file(image, grid);
        // A reference stub (`,fxt_fire_gas_flash` in `common_mp`, streamed by `patch_mp`) carries
        // neither hash: ask by its name's hash, which the packs resolve by name (`Paks::image`).
        let key = if key.data_hash == 0 && key.name_hash == 0 { zhbo_formats::ipak::ImageKey { data_hash: 0, name_hash: zhbo_formats::ipak::r_hash_string(image) } } else { key };
        let Some(rgba) = paks(key) else {
            self.missing.insert(image.to_string());
            return None;
        };
        let rgba = flipbook_grid(&rgba, atlas, grid);
        let opaque = rgba.pixels.as_chunks::<4>().0.iter().all(|p| p[3] >= 250);
        self.textures.entry(format!("Art\\Textures\\{file}")).or_insert_with(|| images::tga_bytes(&rgba));
        Some(Tex { file, opaque, grid })
    }
}

/// A converted effect texture: its file, whether it has no real alpha, and its flipbook grid.
struct Tex {
    file: String,
    opaque: bool,
    grid: Grid,
}

/// The most frames Zero Hour's point group can draw from one texture (a 16 × 16 grid: W3D's
/// `FrameRowColumnCountLog2` is at most 4).
const MAX_FRAMES: u32 = 256;

/// A flipbook as Zero Hour draws it (host patch 0025): `side` cells per side of a square grid
/// (a power of two), `frames` of them in use, row by row from the top left. `side` 1 is a plain
/// texture.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Grid {
    pub side: u32,
    pub frames: u32,
}

impl Grid {
    pub const NONE: Grid = Grid { side: 1, frames: 1 };

    /// The smallest grid holding `frames` cells.
    pub fn of(frames: u32) -> Grid {
        let frames = frames.clamp(1, MAX_FRAMES);
        let mut side = 1;
        while side * side < frames {
            side *= 2;
        }
        Grid { side, frames }
    }
}

/// The converter's texture file for a BO2 image drawn on `grid`.
pub fn texture_file(image: &str, grid: Grid) -> String {
    let base = crate::character::texture_file(image);
    let base = base.trim_start_matches("zhbo_");
    if grid.frames > 1 {
        let stem = base.strip_suffix(".tga").unwrap_or(base);
        format!("zhbo_fx_{stem}_f{}.tga", grid.frames)
    } else {
        format!("zhbo_fx_{base}")
    }
}

/// A BO2 atlas image (`atlas` columns × rows) as the texture Zero Hour draws: the first cell alone
/// for a single frame, else its first `grid.frames` cells (row by row) in `grid`'s square layout.
/// Each cell is shrunk to at most `FX_TEXTURE_MAX`, and to 1024 / `side` in a grid, so a 32-frame
/// fire stays a 1024-pixel texture.
fn flipbook_grid(rgba: &zhbo_formats::iwi::Rgba, atlas: (u32, u32), grid: Grid) -> zhbo_formats::iwi::Rgba {
    use zhbo_formats::iwi::Rgba;
    let (cols, rows) = (atlas.0.max(1), atlas.1.max(1));
    let (cw, ch) = ((rgba.width / cols).max(1), (rgba.height / rows).max(1));
    let cell = |i: u32| -> Rgba {
        let (cx, cy) = (i % cols, (i / cols).min(rows - 1));
        let mut px = vec![0u8; (cw * ch * 4) as usize];
        for y in 0..ch {
            let sy = (cy * ch + y).min(rgba.height - 1);
            let src = ((sy * rgba.width + cx * cw) * 4) as usize;
            let n = (cw * 4) as usize;
            if src + n <= rgba.pixels.len() {
                px[(y * cw * 4) as usize..(y * cw * 4) as usize + n].copy_from_slice(&rgba.pixels[src..src + n]);
            }
        }
        Rgba { width: cw, height: ch, pixels: px }
    };
    if grid.frames <= 1 {
        return crate::generals::shrink(cell(0), FX_TEXTURE_MAX);
    }
    let max_cell = FX_TEXTURE_MAX.min(FX_FLIPBOOK_MAX / grid.side);
    let cells: Vec<Rgba> = (0..grid.frames).map(|i| crate::generals::shrink(cell(i), max_cell)).collect();
    let (w, h) = (cells[0].width, cells[0].height);
    let mut out = Rgba { width: w * grid.side, height: h * grid.side, pixels: vec![0u8; (w * h * grid.side * grid.side * 4) as usize] };
    for (i, c) in cells.iter().enumerate() {
        let (gx, gy) = (i as u32 % grid.side, i as u32 / grid.side);
        for y in 0..h.min(c.height) {
            let dst = (((gy * h + y) * out.width + gx * w) * 4) as usize;
            let n = (w.min(c.width) * 4) as usize;
            out.pixels[dst..dst + n].copy_from_slice(&c.pixels[(y * c.width * 4) as usize..(y * c.width * 4) as usize + n]);
        }
    }
    out
}

