//! A skinned model blob (`.zbm`): one BO2 `XModel` as the mod draws it.
//!
//! Positions are BO2's own units (inches) in model space; the core scales at draw time. Bones keep
//! both their local (parent-relative) and model-space bind transforms, as `XModel` stores them.
//! Every vertex carries up to four bone influences (BO2 skins with at most four).

use crate::io::{FormatError, Reader, Writer};
use crate::math::{Quat, Vec3};

pub const MAGIC: [u8; 4] = *b"ZBM\0";
/// 2: materials carry `cull`. The semantic-22 camo layer is added; the version bump to 3 is
/// integrator-owned (the archive is regenerated by the converter).
pub const VERSION: u32 = 3;

/// No material on a surface.
pub const NO_MATERIAL: u32 = u32::MAX;

/// A vertex's size in the blob: position, normal, UV, four bone indices, four weights.
const VERTEX_BYTES: usize = 12 + 12 + 8 + 4 * 2 + 4 * 4;

#[derive(Clone, Debug, PartialEq)]
pub struct Bone {
    pub name: String,
    pub parent: Option<u32>,
    /// Relative to the parent, as BO2's animations offset it (identity for roots).
    pub local_rotation: Quat,
    pub local_position: Vec3,
    /// Model space, bind pose.
    pub rotation: Quat,
    pub position: Vec3,
}

#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Vertex {
    pub position: Vec3,
    pub normal: Vec3,
    pub uv: [f32; 2],
    /// Indices into the model's bones; unused slots have weight 0.
    pub bones: [u16; 4],
    /// Sum to 1.
    pub weights: [f32; 4],
}

/// How a surface draws over what is behind it: BO2's own render state for its lit technique
/// (`GfxStateBits::loadBits[0]`, read by `zhbo_formats::xmodel::blend_of`; MODLOG #73).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Blend {
    #[default]
    Opaque,
    /// Opaque with alpha test (cutouts: foliage on a stock, mesh grilles).
    AlphaTest,
    /// Source alpha over the destination (glass).
    Alpha,
    Premultiplied,
    /// Added to the destination (glows), scaled by alpha when `alpha`.
    Additive { alpha: bool },
}

impl Blend {
    fn code(self) -> u8 {
        match self {
            Blend::Opaque => 0,
            Blend::AlphaTest => 1,
            Blend::Alpha => 2,
            Blend::Premultiplied => 3,
            Blend::Additive { alpha: false } => 4,
            Blend::Additive { alpha: true } => 5,
        }
    }
    fn from_code(c: u8) -> Result<Blend, FormatError> {
        Ok(match c {
            0 => Blend::Opaque,
            1 => Blend::AlphaTest,
            2 => Blend::Alpha,
            3 => Blend::Premultiplied,
            4 => Blend::Additive { alpha: false },
            5 => Blend::Additive { alpha: true },
            _ => return Err(FormatError::Corrupt(format!("blend {c}"))),
        })
    }
    /// Whether it writes depth (blended surfaces don't, so what is behind them still shows).
    pub fn writes_depth(self) -> bool {
        matches!(self, Blend::Opaque | Blend::AlphaTest)
    }
}

/// Which of a surface's faces draw: the material's `cullFace` (`zhbo_formats::xmodel::Cull`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Cull {
    /// Both (BO2's double-sided: alpha-tested cutouts, glow planes; also the pre-cull default).
    #[default]
    None,
    /// The back faces: BO2's ordinary lit surfaces.
    Back,
    Front,
}

impl Cull {
    fn code(self) -> u8 {
        match self {
            Cull::None => 0,
            Cull::Back => 1,
            Cull::Front => 2,
        }
    }
    fn from_code(c: u8) -> Result<Cull, FormatError> {
        Ok(match c {
            0 => Cull::None,
            1 => Cull::Back,
            2 => Cull::Front,
            _ => return Err(FormatError::Corrupt(format!("cull {c}"))),
        })
    }
}

/// The surface's semantic-22 camo layer's *default* image: what a chosen camo replaces. The
/// converter classifies the image name; the core takes the camo image of the same kind.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CamoLayer {
    /// No camo layer (bullet, glow, clan tag, emblem, lens, reticle, a style material).
    #[default]
    None,
    /// `camo_off_solid`: the flat swatch half of a camo.
    Solid,
    /// `camo_off_pattern`: the tiling pattern half.
    Pattern,
    /// `weapon_camo_neutral`: neither; the reflex optic's `_camo2` group (research §5.2).
    Neutral,
}

impl CamoLayer {
    fn code(self) -> u8 {
        match self {
            CamoLayer::None => 0,
            CamoLayer::Solid => 1,
            CamoLayer::Pattern => 2,
            CamoLayer::Neutral => 3,
        }
    }
    fn from_code(c: u8) -> Result<CamoLayer, FormatError> {
        Ok(match c {
            0 => CamoLayer::None,
            1 => CamoLayer::Solid,
            2 => CamoLayer::Pattern,
            3 => CamoLayer::Neutral,
            _ => return Err(FormatError::Corrupt(format!("camo layer {c}"))),
        })
    }
}

/// Which of BO2's reticle techniques draws a lens reticle (by the material's technique set).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum ReticleKind {
    /// `sw4_3d_reticle_dynamic`: projected to infinity, faded in by the aim (reflex, holo, ACOG,
    /// the dual optic).
    #[default]
    Dynamic,
    /// `sw4_3d_reticle_dynamic_2colors`: projected, no aim fade, its colours lerped to the `alt`
    /// pair by `weaponParam0.z` (the target finder's second reticle: the `rangefinder` attachment, BO2's Target Finder).
    TwoColors,
    /// `sw4_3d_reticle_static`: the image at the lens's own UVs, screen-space noise, no aim fade
    /// (the MMS).
    Static,
    /// `sw4_3d_reticle_ui3d`: a code-drawn UI texture (`ui3dSampler`) at the lens UVs, two shapes
    /// and two glows in its four channels, added (the target finder's display). There is no image of
    /// its own; without the code's texture it adds nothing.
    Ui3d,
}

impl ReticleKind {
    fn code(self) -> u8 {
        match self {
            ReticleKind::Dynamic => 0,
            ReticleKind::TwoColors => 1,
            ReticleKind::Static => 2,
            ReticleKind::Ui3d => 3,
        }
    }
    fn from_code(c: u8) -> Result<ReticleKind, FormatError> {
        Ok(match c {
            0 => ReticleKind::Dynamic,
            1 => ReticleKind::TwoColors,
            2 => ReticleKind::Static,
            3 => ReticleKind::Ui3d,
            _ => return Err(FormatError::Corrupt(format!("reticle kind {c}"))),
        })
    }
}

/// BO2's lens reticle (the `sw4_3d_reticle_dynamic` techset: reflex, holo, ACOG, the dual optic's
/// halves; the other reticle techniques by [`ReticleKind`]). The surface's colour map is the reticle image — red its shape, green its glow, blue
/// the background's coverage — and it is not mapped by the lens's UVs: the vertex shader projects
/// it to infinity, `0.5 + scale · (T·v, −B·v)` for the eye→surface direction `v` in the surface's
/// tangent frame, so it sits on the optic's axis wherever the eye is (parallax-free). The numbers
/// are the material's own constants, by the shader's names (DXBC of
/// `pimp_shader_sw4_3d_reticle_dynamic_*`, MODLOG "The optic reticle on the lens").
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Reticle {
    /// `Color_Map_Scale`: reticle image widths per radian off the axis.
    pub scale: f32,
    /// `Reticle_Color`: the shape's colour (HDR: above 1 saturates to a white-hot core).
    pub color: [f32; 3],
    /// `Glow_Color` and `Glow_Falloff`: the glow is `green^falloff · Glow_Color`.
    pub glow: [f32; 3],
    pub glow_falloff: f32,
    /// `Emissive_Amount`: the whole reticle's gain.
    pub emissive: f32,
    /// `Noise_Scale` and `Color_Map_Noise`: the noise map, tiled over the lens UVs, modulates the
    /// glow and dims the shape by `1 − amount · noise`.
    pub noise_scale: f32,
    pub noise_amount: f32,
    /// `Background`: the blue channel's coverage (the alpha of a premultiplied blend).
    pub background: f32,
    /// The noise map (`Detail_Map`), raw; `None` draws without noise (white).
    pub noise: Option<String>,
    pub kind: ReticleKind,
    /// `Reticle_Alt_Color` and `Glow_Alt_Color` (two-colour and ui3d techniques; 0 otherwise).
    pub color_alt: [f32; 3],
    pub glow_alt: [f32; 3],
}

impl Reticle {
    fn write(&self, w: &mut Writer) {
        w.f32(self.scale);
        w.f32s(&self.color);
        w.f32s(&self.glow);
        for v in [self.glow_falloff, self.emissive, self.noise_scale, self.noise_amount, self.background] {
            w.f32(v);
        }
        w.opt_str(self.noise.as_deref());
        w.u8(self.kind.code());
        w.f32s(&self.color_alt);
        w.f32s(&self.glow_alt);
    }
    fn read(r: &mut Reader) -> Result<Reticle, FormatError> {
        Ok(Reticle {
            scale: r.f32()?,
            color: r.f32n()?,
            glow: r.f32n()?,
            glow_falloff: r.f32()?,
            emissive: r.f32()?,
            noise_scale: r.f32()?,
            noise_amount: r.f32()?,
            background: r.f32()?,
            noise: r.opt_str()?,
            kind: ReticleKind::from_code(r.u8()?)?,
            color_alt: r.f32n()?,
            glow_alt: r.f32n()?,
        })
    }
}

/// BO2's millimetre-scanner screen (the `sw4_3d_sonar_attachment_lens2` techset:
/// `mc/mtl_t6_attach_optic_mms_display`). It is drawn in screen space from the scene's view depth
/// (its outlines and a pulse ring sweeping out from the eye) and from the characters the code puts
/// on the scanner (shown only behind walls); the numbers are the material's own constants, by the
/// shader's names (DXBC of `pimp_shader_sw4_3d_sonar_attachment_lens2_fc8afb12`, MODLOG "The MMS
/// screen"). Distances are BO2 inches.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Sonar {
    /// `Lookup` (the pulse's profile along U: green the characters', red the ring's, blue the
    /// outline's) and `Static_Noise_Map`, raw; `None` draws white.
    pub lookup: Option<String>,
    pub noise: Option<String>,
    /// `PulseInterval`, `PulseTime`, `MaxDepth`, `MaxPulseDepth`.
    pub pulse: [f32; 4],
    /// `MinDepth`, `LineNoise`, `BackgroundNoise`, `hdrAmount`.
    pub depth: [f32; 4],
    /// `ScatterSize` (the noise's tiling over the mesh UVs).
    pub scatter: [f32; 2],
    /// `EdgeSize`, `EdgeIntensity`, `EdgeMinDist`, `EdgeMaxDist`.
    pub edge: [f32; 4],
    /// `Pulse_Lookup_Scale`, `Player_Lookup_Scale`, `Outline_Lookup_Scale`, `Min_Player_Intensity`.
    pub lookup_scale: [f32; 4],
    /// `EnemiesColor` and `Player_Color_Multiplier`.
    pub enemies: [f32; 4],
    /// `PulseColor` and `Pulse_Color_Multiplier`.
    pub pulse_color: [f32; 4],
    /// `EdgeColor` and `Edge_Color_Multiplier`.
    pub edge_color: [f32; 4],
}

impl Sonar {
    /// Every constant, in the record's order.
    pub fn constants(&self) -> [f32; 30] {
        let mut out = [0.0; 30];
        let all = self.pulse.iter().chain(&self.depth).chain(&self.scatter).chain(&self.edge).chain(&self.lookup_scale).chain(&self.enemies).chain(&self.pulse_color).chain(&self.edge_color);
        for (o, v) in out.iter_mut().zip(all) {
            *o = *v;
        }
        out
    }
    fn write(&self, w: &mut Writer) {
        w.opt_str(self.lookup.as_deref());
        w.opt_str(self.noise.as_deref());
        w.f32s(&self.constants());
    }
    fn read(r: &mut Reader) -> Result<Sonar, FormatError> {
        let lookup = r.opt_str()?;
        let noise = r.opt_str()?;
        let c: [f32; 30] = r.f32n()?;
        let q = |i: usize| [c[i], c[i + 1], c[i + 2], c[i + 3]];
        Ok(Sonar { lookup, noise, pulse: q(0), depth: q(4), scatter: [c[8], c[9]], edge: q(10), lookup_scale: q(14), enemies: q(18), pulse_color: q(22), edge_color: q(26) })
    }
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Material {
    /// BO2's material name (for logs).
    pub name: String,
    pub blend: Blend,
    /// Self-lit (glows, screens): drawn at full colour, no lighting.
    pub emissive: bool,
    /// The colour map's file in the archive (`Art\Textures\...`), sRGB. Opaque surfaces carry their
    /// ambient occlusion in its alpha (`zhbo_assets::textures::put_occlusion`).
    pub color: Option<String>,
    /// The packed surface maps (`*_nsg.tga`: normal X, normal Y, gloss, specular level;
    /// `zhbo_assets::textures::surface_maps`), linear.
    pub maps: Option<String>,
    /// BO2's sort key (draw order of blended surfaces).
    pub sort_key: u8,
    /// Which faces draw (R4; the material's `cullFace`).
    pub cull: Cull,
    /// The surface's camo layer default (semantic 22): which camo image a pattern camo uses.
    pub camo: CamoLayer,
    /// BO2's specular colour (`*_spec.tga`: the spec map's RGB at its own size, raw like `maps`;
    /// `zhbo_assets::textures::specular_color`), or `None` for the packed maps' scalar level. A
    /// metal's hue lives here: gold's colour map is a flat dark, its spec map gold. Appended to
    /// the record (model `VERSION` 3 -> 4 and camo `VERSION` 1 -> 2 are integrator-owned).
    pub specular: Option<String>,
    /// The lens reticle's projection and constants, for a reticle surface (appended with
    /// `emblem`; the model/camo `VERSION` bumps are integrator-owned).
    pub reticle: Option<Reticle>,
    /// BO2's emblem surface (`sw4_3d_player_icon`): the core draws the player's faction emblem on
    /// it in place of the material's own stand-in (`emblem_clear`).
    pub emblem: bool,
    /// The MMS screen's technique and constants, for its display surface (appended after
    /// `emblem`; the model/camo `VERSION` bumps are integrator-owned).
    pub sonar: Option<Sonar>,
}

impl Material {
    /// Write one material record. Shared by the model and camo blobs so their encodings cannot
    /// drift.
    pub fn write(&self, w: &mut Writer) {
        w.str(&self.name);
        w.u8(self.blend.code());
        w.u8(self.emissive as u8);
        w.opt_str(self.color.as_deref());
        w.opt_str(self.maps.as_deref());
        w.u8(self.sort_key);
        w.u8(self.cull.code());
        w.u8(self.camo.code());
        w.opt_str(self.specular.as_deref());
        match &self.reticle {
            None => w.u8(0),
            Some(r) => {
                w.u8(1);
                r.write(w);
            }
        }
        w.u8(self.emblem as u8);
        match &self.sonar {
            None => w.u8(0),
            Some(s) => {
                w.u8(1);
                s.write(w);
            }
        }
    }
    /// Read one material record written by [`Self::write`].
    pub fn read(r: &mut Reader) -> Result<Material, FormatError> {
        Ok(Material {
            name: r.str()?,
            blend: Blend::from_code(r.u8()?)?,
            emissive: r.u8()? != 0,
            color: r.opt_str()?,
            maps: r.opt_str()?,
            sort_key: r.u8()?,
            cull: Cull::from_code(r.u8()?)?,
            camo: CamoLayer::from_code(r.u8()?)?,
            specular: r.opt_str()?,
            reticle: match r.u8()? {
                0 => None,
                1 => Some(Reticle::read(r)?),
                v => return Err(FormatError::Corrupt(format!("reticle tag {v}"))),
            },
            emblem: match r.u8()? {
                0 => false,
                1 => true,
                v => return Err(FormatError::Corrupt(format!("emblem flag {v}"))),
            },
            sonar: match r.u8()? {
                0 => None,
                1 => Some(Sonar::read(r)?),
                v => return Err(FormatError::Corrupt(format!("sonar tag {v}"))),
            },
        })
    }
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Surface {
    pub material: u32,
    pub vertices: Vec<Vertex>,
    pub indices: Vec<u16>,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Lod {
    pub distance: f32,
    pub first_surface: u32,
    pub surface_count: u32,
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Model {
    pub name: String,
    pub bones: Vec<Bone>,
    pub materials: Vec<Material>,
    pub lods: Vec<Lod>,
    /// All LODs' surfaces; `lods` says which belong to which.
    pub surfaces: Vec<Surface>,
    pub mins: Vec3,
    pub maxs: Vec3,
    pub radius: f32,
}

impl Model {
    /// The surfaces of LOD 0 (the one a viewmodel draws).
    pub fn lod0(&self) -> &[Surface] {
        match self.lods.first() {
            Some(l) => {
                let a = (l.first_surface as usize).min(self.surfaces.len());
                let b = (a + l.surface_count as usize).min(self.surfaces.len());
                &self.surfaces[a..b]
            }
            None => &self.surfaces,
        }
    }

    pub fn bone(&self, name: &str) -> Option<usize> {
        self.bones.iter().position(|b| b.name == name)
    }

    pub fn to_bytes(&self) -> Vec<u8> {
        let mut w = Writer::header(MAGIC, VERSION);
        w.str(&self.name);
        w.count(self.bones.len());
        for b in &self.bones {
            w.str(&b.name);
            w.u32(b.parent.unwrap_or(u32::MAX));
            w.f32s(&b.local_rotation);
            w.f32s(&b.local_position);
            w.f32s(&b.rotation);
            w.f32s(&b.position);
        }
        w.count(self.materials.len());
        for m in &self.materials {
            m.write(&mut w);
        }
        w.count(self.lods.len());
        for l in &self.lods {
            w.f32(l.distance);
            w.u32(l.first_surface);
            w.u32(l.surface_count);
        }
        w.count(self.surfaces.len());
        for s in &self.surfaces {
            w.u32(s.material);
            w.count(s.vertices.len());
            for v in &s.vertices {
                w.f32s(&v.position);
                w.f32s(&v.normal);
                w.f32s(&v.uv);
                for b in v.bones {
                    w.u16(b);
                }
                w.f32s(&v.weights);
            }
            w.count(s.indices.len());
            for i in &s.indices {
                w.u16(*i);
            }
        }
        w.f32s(&self.mins);
        w.f32s(&self.maxs);
        w.f32(self.radius);
        w.bytes
    }

    /// Read and validate a model blob: bone parents come before their children, every index is in
    /// range, every surface's material exists.
    pub fn from_bytes(data: &[u8]) -> Result<Model, FormatError> {
        let mut r = Reader::open(data, MAGIC, "model", VERSION)?;
        let name = r.str()?;
        let nb = r.count(4 + 4 + 56)?;
        let mut bones = Vec::with_capacity(nb);
        for i in 0..nb {
            let name = r.str()?;
            let parent = match r.u32()? {
                u32::MAX => None,
                p if (p as usize) < i => Some(p),
                p => return Err(FormatError::Corrupt(format!("bone {i} has parent {p}"))),
            };
            bones.push(Bone { name, parent, local_rotation: r.f32n()?, local_position: r.f32n()?, rotation: r.f32n()?, position: r.f32n()? });
        }
        let nm = r.count(10)?;
        let mut materials = Vec::with_capacity(nm);
        for _ in 0..nm {
            materials.push(Material::read(&mut r)?);
        }
        let nl = r.count(12)?;
        let mut lods = Vec::with_capacity(nl);
        for _ in 0..nl {
            lods.push(Lod { distance: r.f32()?, first_surface: r.u32()?, surface_count: r.u32()? });
        }
        let ns = r.count(12)?;
        let mut surfaces = Vec::with_capacity(ns);
        for si in 0..ns {
            let material = r.u32()?;
            if material != NO_MATERIAL && material as usize >= materials.len() {
                return Err(FormatError::Corrupt(format!("surface {si} uses material {material} of {}", materials.len())));
            }
            let nv = r.count(VERTEX_BYTES)?;
            let mut vertices = Vec::with_capacity(nv);
            for _ in 0..nv {
                let position = r.f32n()?;
                let normal = r.f32n()?;
                let uv = r.f32n()?;
                let mut vb = [0u16; 4];
                for b in &mut vb {
                    *b = r.u16()?;
                    if *b as usize >= nb.max(1) {
                        return Err(FormatError::Corrupt(format!("surface {si} skins to bone {b} of {nb}")));
                    }
                }
                vertices.push(Vertex { position, normal, uv, bones: vb, weights: r.f32n()? });
            }
            let ni = r.count(2)?;
            if ni % 3 != 0 {
                return Err(FormatError::Corrupt(format!("surface {si} has {ni} indices")));
            }
            let mut indices = Vec::with_capacity(ni);
            for _ in 0..ni {
                let i = r.u16()?;
                if i as usize >= nv {
                    return Err(FormatError::Corrupt(format!("surface {si} index {i} of {nv} vertices")));
                }
                indices.push(i);
            }
            surfaces.push(Surface { material, vertices, indices });
        }
        for (i, l) in lods.iter().enumerate() {
            if l.first_surface as u64 + l.surface_count as u64 > surfaces.len() as u64 {
                return Err(FormatError::Corrupt(format!("lod {i} past the surfaces")));
            }
        }
        let model = Model { name, bones, materials, lods, surfaces, mins: r.f32n()?, maxs: r.f32n()?, radius: r.f32()? };
        r.finish()?;
        Ok(model)
    }
}

