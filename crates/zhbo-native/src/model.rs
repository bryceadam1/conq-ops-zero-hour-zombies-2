    fn round_trips() {
        let m = strip();
        let bytes = m.to_bytes();
        assert_eq!(Model::from_bytes(&bytes).unwrap(), m);
        // Every prefix is refused, never a panic.
        for n in 0..bytes.len() {
            assert!(Model::from_bytes(&bytes[..n]).is_err(), "prefix {n}");
        }
        let mut longer = bytes.clone();
        longer.push(0);
        assert!(Model::from_bytes(&longer).is_err(), "trailing bytes");
    }

    #[test]
    fn the_camo_layer_round_trips() {
        for layer in [CamoLayer::None, CamoLayer::Solid, CamoLayer::Pattern, CamoLayer::Neutral] {
            let mut m = strip();
            m.materials[0].camo = layer;
            assert_eq!(Model::from_bytes(&m.to_bytes()).unwrap(), m, "{layer:?}");
        }
        // The codes are the blob's contract; a wrong one must be refused, not defaulted.
        assert_eq!(CamoLayer::from_code(2).unwrap(), CamoLayer::Pattern);
        assert!(CamoLayer::from_code(4).is_err());
    }

