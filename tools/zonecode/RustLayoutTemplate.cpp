#include "RustLayoutTemplate.h"

#include "Domain/Definition/ArrayDeclarationModifier.h"
#include "Domain/Definition/DefinitionWithMembers.h"
#include "Domain/Definition/TypedefDefinition.h"

#include <set>
#include <string>
#include <vector>

namespace
{
    const DataDefinition* Resolve(const DataDefinition* t)
    {
        while (const auto* td = dynamic_cast<const TypedefDefinition*>(t))
            t = td->m_type_declaration->m_type;
        return t;
    }

    std::string RustName(const std::string& name)
    {
        static const std::set<std::string> keywords = {"type", "ref", "move", "match", "loop", "use", "mod", "fn", "impl", "struct", "enum", "trait", "self", "Self", "in", "box", "where", "static", "const", "crate", "super", "as", "break", "continue", "else", "extern", "false", "true", "for", "if", "let", "mut", "pub", "return", "unsafe", "while", "async", "await", "dyn", "abstract", "become", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try"};
        return keywords.contains(name) ? "r#" + name : name;
    }

    void Collect(const DefinitionWithMembers* def, std::vector<const DefinitionWithMembers*>& out, std::set<const DefinitionWithMembers*>& seen)
    {
        if (!def || seen.contains(def))
            return;
        seen.insert(def);
        out.push_back(def);
        for (const auto& m : def->m_members)
            Collect(dynamic_cast<const DefinitionWithMembers*>(Resolve(m->m_type_declaration->m_type)), out, seen);
    }
} // namespace

std::vector<CodeTemplateFile> RustLayoutTemplate::GetFilesToRenderOncePerTemplate(const OncePerTemplateRenderingContext& context)
{
    std::vector<CodeTemplateFile> files;
    files.emplace_back("layouts.rs", 0);
    return files;
}

void RustLayoutTemplate::RenderOncePerTemplateFile(std::ostream& stream, CodeTemplateFileTag fileTag, const OncePerTemplateRenderingContext& context)
{
    std::vector<const DefinitionWithMembers*> defs;
    std::set<const DefinitionWithMembers*> seen;
    for (const auto* asset : context.m_assets)
        Collect(asset->m_definition, defs, seen);

    stream << "// Generated by OpenAssetTools' ZoneCodeGenerator with tools/zonecode/RustLayoutTemplate.cpp.\n"
              "// T6 struct sizes and field offsets (32-bit PC). Do not edit.\n"
              "#![allow(non_snake_case, non_upper_case_globals, dead_code)]\n\n";
    for (const auto* def : defs)
    {
        stream << "pub mod " << def->m_name << " {\n";
        stream << "    pub const SIZE: u32 = " << def->GetSize() << ";\n";
        std::set<std::string> names;
        for (const auto& m : def->m_members)
        {
            if (m->m_name.empty() || names.contains(m->m_name))
                continue;
            names.insert(m->m_name);
            const auto* t = Resolve(m->m_type_declaration->m_type);
            std::string dims;
            bool pointer = false;
            for (const auto& mod : m->m_type_declaration->m_declaration_modifiers)
            {
                if (mod->GetType() == DeclarationModifierType::ARRAY)
                    dims += "[" + std::to_string(dynamic_cast<ArrayDeclarationModifier*>(mod.get())->m_size) + "]";
                else
                    pointer = true;
            }
            stream << "    pub const " << RustName(m->m_name) << ": u32 = " << m->m_offset << "; // " << t->m_name << (pointer ? "*" : "") << dims << "\n";
        }
        stream << "}\n";
    }
}

